"""reports/metrics.json is the only source of reported numbers."""
from __future__ import annotations

import json
import subprocess
import sys

import pytest

from supplyiq.paths import METRICS_FILE, REPO_ROOT


@pytest.fixture(scope="module")
def metrics() -> dict:
    if not METRICS_FILE.exists():
        pytest.skip("reports/metrics.json not built; run `make metrics`")
    return json.loads(METRICS_FILE.read_text())


def test_metrics_file_is_committed(metrics):
    assert metrics["_about"].startswith("Generated by `make metrics`")


def test_metrics_record_their_provenance(metrics):
    prov = metrics["data_provenance"]
    assert prov["origin"] in {"kaggle", "synthetic"}
    assert prov["is_real_data"] == (prov["origin"] == "kaggle")
    assert "simulated" in prov["label"].lower()
    assert "suppliers" in prov["simulated_sections"]
    assert "costs" in prov["simulated_sections"]


def test_metrics_match_the_committed_sample(metrics, tables, assumptions):
    data = metrics["data"]
    assert data["planning_items"] == len(tables["sku_master"])
    assert data["demand_rows"] == len(tables["demand"])
    assert data["purchase_order_rows"] == len(tables["purchase_orders"])
    assert data["suppliers"] == len(tables["suppliers"])
    assert data["weeks_of_history"] == assumptions["sample"]["n_weeks"]


def test_holdout_in_metrics_matches_the_configured_split(metrics, assumptions):
    first, last = metrics["data"]["holdout_weeks"]
    assert last - first + 1 == assumptions["sample"]["holdout_weeks"]
    assert metrics["data"]["train_weeks"][1] == first - 1


def test_supplier_performance_is_recomputable(metrics, tables):
    po = tables["purchase_orders"]
    otif = float(((po["late_delivery"] == 0) & (po["in_full"] == 1)).mean())
    assert metrics["supplier_performance"]["overall_otif"] == pytest.approx(otif, abs=1e-4)


def test_cost_model_states_its_formulas(metrics):
    cost = metrics["cost_model"]
    assert cost["simulated"] is True
    assert "sell_price" in cost["formula_unit_cost"]
    assert "tariff_rate" in cost["formula_landed_cost"]


def test_metrics_declare_which_phases_are_complete(metrics):
    assert metrics["phases_complete"] == [1, 2, 3]
    assert set(metrics["pending_phases"]) == {"4"}


