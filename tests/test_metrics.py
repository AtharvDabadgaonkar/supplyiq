def test_readme_metrics_block_is_in_sync(metrics):
    """Regenerating the block must be a no-op, or the README is stale."""
    from scripts.render_readme import END, START, render

    readme = (REPO_ROOT / "README.md").read_text()
    assert START in readme and END in readme
    current = readme[readme.index(START) : readme.index(END) + len(END)]
    expected = render(metrics)

    def strip_timestamp(block: str) -> list[str]:
        return [ln for ln in block.splitlines() if "generated by" not in ln]

    assert strip_timestamp(current) == strip_timestamp(expected), (
        "README metrics block is stale; run `make metrics`"
    )


