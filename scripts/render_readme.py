#!/usr/bin/env python
"""Render the README's metrics block from reports/metrics.json.

Called at the end of `make metrics`, so a reported number can never drift from
the figure the pipeline actually computed. The block between the two markers is
generated; everything else in the README is hand-written.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from supplyiq.paths import METRICS_FILE, REPO_ROOT  # noqa: E402

README = REPO_ROOT / "README.md"
START = "<!-- METRICS:START -->"
END = "<!-- METRICS:END -->"


def render(m: dict) -> str:
    prov = m["data_provenance"]
    d, sp, cm = m["data"], m["supplier_performance"], m["cost_model"]
    real = "**real (M5 + DataCo)**" if prov["is_real_data"] else "**synthetic placeholder**"
    phases = ", ".join(str(p) for p in m["phases_complete"])

    lines = [
        START,
        f"<!-- generated by scripts/render_readme.py from reports/metrics.json at "
        f"{m['generated_at']} — do not edit by hand -->",
        "",
        f"Demand data is {real}. Supplier lead times, unit costs, freight and tariff "
        "rates are **simulated** on top of it, from `config/assumptions.yaml`.",
        "",
        "| Metric | Value | Source |",
        "| --- | --- | --- |",
        f"| Planning items (SKU × store) | {d['planning_items']:,} | real |"
        if prov["is_real_data"]
        else f"| Planning items (SKU × store) | {d['planning_items']:,} | simulated |",
        f"| Weeks of history | {d['weeks_of_history']} "
        f"({d['week_start_first']} → {d['week_start_last']}) | "
        f"{'real' if prov['is_real_data'] else 'simulated'} |",
        f"| Holdout window | weeks {d['holdout_weeks'][0]}–{d['holdout_weeks'][1]} "
        f"(never used in training) | method |",
        f"| Total units sold | {d['total_units_sold']:,} | "
        f"{'real' if prov['is_real_data'] else 'simulated'} |",
        f"| Weeks with zero demand | {d['zero_demand_week_share']:.1%} | "
        f"{'real' if prov['is_real_data'] else 'simulated'} |",
        f"| Median demand CV per item | {d['demand_cv_median']:.2f} | derived |",
        f"| Suppliers | {d['suppliers']} | simulated |",
        f"| Historical OTIF | {sp['overall_otif']:.1%} | simulated |",
        f"| Late-delivery rate | {sp['overall_late_delivery_rate']:.1%} | simulated |",
        f"| Mean inbound lead time | {sp['lead_time_mean_days']:.1f} days | simulated |",
        f"| Mean landed cost / unit | ${cm['mean_landed_cost']:.2f} | simulated |",
        f"| Landed vs. ex-works cost uplift | {cm['landed_vs_unit_cost_uplift_pct']:.1f}% | simulated |",
        f"| Items exposed to tariffs | {cm['tariff_exposed_share']:.1%} "
        f"({cm['items_exposed_to_tariff']:,} items) | simulated |",
    ]

    fc = m.get("forecast_accuracy")
    if fc:
        base = fc["models"][fc["baseline_model"]]
        cand = fc["models"][fc["candidate_model"]]
        lines += [
            "",
            "**Forecast accuracy** — fitted on the training weeks, scored on the untouched holdout.",
            "",
            "| Model | WAPE | MAPE | Bias | RMSE |",
            "| --- | --- | --- | --- | --- |",
            f"| `{fc['baseline_model']}` (baseline) | {base['wape']:.3f} | {base['mape']:.3f} | "
            f"{base['bias_pct']:+.3f} | {base['rmse']:.2f} |",
            f"| `{fc['candidate_model']}` (candidate) | **{cand['wape']:.3f}** | {cand['mape']:.3f} | "
            f"{cand['bias_pct']:+.3f} | {cand['rmse']:.2f} |",
            "",
            f"The candidate takes **{fc['wape_improvement_pp']:.1f} percentage points** off the "
            f"baseline's WAPE, a {fc['wape_improvement_pct_of_baseline']:.0f}% relative "
            f"improvement. {fc['mape_note']}",
        ]

    inv = m.get("inventory_policy")
    if inv:
        lines += [
            "",
            "**Inventory policy** — at the configured service levels "
            f"(A {inv['service_level_by_abc']['A']:.0%}, B {inv['service_level_by_abc']['B']:.0%}, "
            f"C {inv['service_level_by_abc']['C']:.0%}).",
            "",
            "| Metric | Value |",
            "| --- | --- |",
            f"| Projected fill rate (demand weighted) | {inv['weighted_fill_rate']:.2%} |",
            f"| Portfolio inventory turns | {inv['portfolio_inventory_turns']:.1f} |",
            f"| Median weeks of supply | {inv['median_weeks_of_supply']:.1f} |",
            f"| Total safety stock | {inv['total_safety_stock_units']:,.0f} units "
            f"(${inv['total_safety_stock_value']:,.0f}) |",
            f"| Average inventory value | ${inv['total_average_inventory_value']:,.0f} |",
            f"| **Safety stock added by lead-time variability** | "
            f"**+{inv['leadtime_risk_uplift_pct']:.1f}%** vs. a demand-only formula |",
            "",
            f"That last row is the point of the PLAN module: ignoring lead-time variability — "
            f"which a flat weeks-of-cover rule does — would under-protect this portfolio by "
            f"{inv['leadtime_risk_uplift_pct']:.1f}% of its safety stock, concentrated on the "
            "long overseas lanes.",
        ]

    lines += [
        "",
        f"_Phases complete: {phases} of 5. Scenario and backtest figures appear here as those "
        "phases land._",
        "",
        END,
    ]
    return "\n".join(lines)


def main() -> int:
    if not METRICS_FILE.exists():
        print("reports/metrics.json not found; run scripts/metrics.py first", file=sys.stderr)
        return 1
    if not README.exists():
        print("README.md not found", file=sys.stderr)
        return 1

    metrics = json.loads(METRICS_FILE.read_text())
    text = README.read_text()
    if START not in text or END not in text:
        print(f"README.md must contain the markers {START} and {END}", file=sys.stderr)
        return 1

    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    README.write_text(head + render(metrics) + tail, encoding="utf-8")
    print(f"updated the metrics block in {README.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
